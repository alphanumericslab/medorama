#!/usr/bin/env python3
"""Generate viewers/vitalstream/cpp/vitalstream/src/timezones.cpp: the IANA time-zone names vitalstream-cpp accepts
for its `timezone` setting (the Python viewer checks names with zoneinfo, the Rust viewer with
chrono-tz; C++20's time-zone database is not available in every standard library).

    python3 tools/gen_timezones.py      # uses this Python's zoneinfo database
"""

import zoneinfo
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'viewers' / 'vitalstream' / 'cpp' / 'vitalstream' / 'src' / 'timezones.cpp'


def main():
    names = sorted(zoneinfo.available_timezones() | {'UTC'})
    body = ''.join(f'    "{n}",\n' for n in names)
    OUT.write_text(f'''// Generated by tools/gen_timezones.py: do not edit.
// IANA time-zone names ({len(names)}), for validating the `timezone` setting.
#include <algorithm>
#include <cstring>
#include <iterator>
#include <string>

#include "settings.hpp"

namespace vitalstream::viewer {{

namespace {{
const char* const NAMES[] = {{
{body}}};
}}  // namespace

bool valid_timezone(const std::string& name) {{
  return std::binary_search(std::begin(NAMES), std::end(NAMES), name.c_str(),
                            [](const char* a, const char* b) {{ return std::strcmp(a, b) < 0; }});
}}

}}  // namespace vitalstream::viewer
''', encoding='utf-8', newline='\n')
    print(f'{OUT.relative_to(OUT.parents[3])}: {len(names)} names')


if __name__ == '__main__':
    main()
